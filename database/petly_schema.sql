CREATE DATABASE IF NOT EXISTS petly DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE petly;

CREATE TABLE IF NOT EXISTS pets (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  name VARCHAR(64) NOT NULL,
  type VARCHAR(64) NOT NULL,
  age VARCHAR(32) NULL,
  weight DECIMAL(6,2) NULL,
  days_together INT UNSIGNED NOT NULL DEFAULT 0,
  next_visit DATE NULL,
  avatar_url VARCHAR(512) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_pets_openid (openid)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS care_tasks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  pet_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(128) NOT NULL,
  time_text VARCHAR(128) NOT NULL,
  kind VARCHAR(32) NOT NULL DEFAULT 'health',
  kind_label VARCHAR(32) NOT NULL DEFAULT '提醒',
  done TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_tasks_user_pet (openid, pet_id),
  CONSTRAINT fk_tasks_pet FOREIGN KEY (pet_id) REFERENCES pets (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS pet_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  pet_id BIGINT UNSIGNED NOT NULL,
  record_type VARCHAR(32) NOT NULL,
  detail VARCHAR(512) NOT NULL,
  value DECIMAL(8,2) NULL,
  record_date DATE NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_records_user_pet (openid, pet_id),
  CONSTRAINT fk_records_pet FOREIGN KEY (pet_id) REFERENCES pets (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS reminders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  pet_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(128) NOT NULL,
  time_text VARCHAR(128) NOT NULL,
  kind VARCHAR(32) NOT NULL DEFAULT 'health',
  done TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_reminders_user_pet (openid, pet_id),
  CONSTRAINT fk_reminders_pet FOREIGN KEY (pet_id) REFERENCES pets (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS community_posts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  author_name VARCHAR(64) NOT NULL,
  avatar VARCHAR(32) NULL,
  text_content VARCHAR(1000) NOT NULL,
  image_emoji VARCHAR(32) NULL,
  image_tone VARCHAR(32) NULL,
  likes INT UNSIGNED NOT NULL DEFAULT 0,
  comments INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_posts_created (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS post_likes (
  post_id BIGINT UNSIGNED NOT NULL,
  openid VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (post_id, openid),
  CONSTRAINT fk_likes_post FOREIGN KEY (post_id) REFERENCES community_posts (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS post_comments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  post_id BIGINT UNSIGNED NOT NULL,
  openid VARCHAR(64) NOT NULL,
  content VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_comments_post (post_id, created_at),
  CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES community_posts (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS user_follows (
  follower_openid VARCHAR(64) NOT NULL,
  followed_openid VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (follower_openid, followed_openid)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS user_settings (
  openid VARCHAR(64) NOT NULL,
  daily_reminder TINYINT(1) NOT NULL DEFAULT 1,
  community_notice TINYINT(1) NOT NULL DEFAULT 1,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (openid)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS service_bookings (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  openid VARCHAR(64) NOT NULL,
  service_name VARCHAR(128) NOT NULL,
  service_type VARCHAR(64) NOT NULL,
  booking_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_bookings_user (openid, created_at)
) ENGINE=InnoDB;
